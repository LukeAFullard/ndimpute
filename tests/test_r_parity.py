"""
Parity with genuine R output (generated by validation/11_r_parity/generate_r_parity.R).

* NADA::ros (v1.6-1.1): plotting positions and $modeled, 60 datasets
  (lognormal / normal, n = 12/30/100, single / multiple detection limits).
* survival::survreg: intercept-only MLE for weibull / lognormal / gaussian with
  right, left, mixed and interval censoring (36 datasets), and conditional means
  E[X | lo < X < hi] computed in R by numerical integration.
"""
import os
import warnings

import numpy as np
import pandas as pd
import pytest

from ndimpute._ros_left import impute_ros_left, hirsch_stedinger_ppoints
from ndimpute._parametric import fit_parametric, impute_parametric_bounds, log_likelihood

DATA = os.path.join(os.path.dirname(__file__), '..', 'validation', '11_r_parity', 'data')


def _read(name):
    path = os.path.join(DATA, name)
    if not os.path.exists(path):
        pytest.fail(f"R reference file {name} not found; regenerate with "
                    "validation/11_r_parity/generate_r_parity.R")
    return pd.read_csv(path)


@pytest.fixture(scope='module')
def nada():
    df = _read('nada_ros.csv')
    df['censored'] = df['censored'].astype(str).str.upper() == 'TRUE'
    return df


def test_nada_plotting_positions(nada):
    for _, d in nada.groupby('dataset'):
        pp, _ = hirsch_stedinger_ppoints(d['value'].values, d['censored'].values)
        np.testing.assert_allclose(pp, d['r_pp'].values, rtol=0, atol=1e-12)


def test_nada_modeled_values(nada):
    for _, d in nada.groupby('dataset'):
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            out = impute_ros_left(d['value'].values, d['censored'].values, dist=d['dist'].iloc[0],
                                  impute_type='quantile', clamp=False)
        np.testing.assert_allclose(out, d['r_modeled'].values, rtol=1e-10, atol=1e-10)


@pytest.fixture(scope='module')
def survreg():
    fits = _read('survreg_fits.csv')
    means = _read('survreg_cond_means.csv')
    return fits, means


def _dist_name(r_dist):
    return {'gaussian': 'normal'}.get(r_dist, r_dist)


def test_survreg_mle_parameters(survreg):
    fits, means = survreg
    for _, f in fits.iterrows():
        d = means[means['dataset'] == f['dataset']]
        dist = _dist_name(f['dist'])
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            fit = fit_parametric(d['lo'].values, d['hi'].values, dist=dist)
        p = fit['params']
        got = (p['shape'], p['scale']) if dist == 'weibull' else (p['mu'], p['sigma'])
        np.testing.assert_allclose(got, (f['p1'], f['p2']), rtol=2e-4,
                                   err_msg=f"dataset {f['dataset']} {dist} {f['ctype']}")
        # Log-likelihood on the original scale must match survreg's
        ll = log_likelihood(fit, d['lo'].values, d['hi'].values)
        assert abs(ll - f['loglik']) < 1e-3 * max(1.0, abs(f['loglik']))


def test_survreg_conditional_means(survreg):
    fits, means = survreg
    for ds, d in means.groupby('dataset'):
        dist = _dist_name(d['dist'].iloc[0])
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            imp = impute_parametric_bounds(d['lo'].values, d['hi'].values, dist=dist, impute_type='mean')
        c = d['r_cond_mean'].notna().values
        # Parameters agree to ~1e-4, so conditional means agree to the same order.
        np.testing.assert_allclose(imp[c], d['r_cond_mean'].values[c], rtol=5e-4,
                                   err_msg=f"dataset {ds} {dist} {d['ctype'].iloc[0]}")


def test_lwptrends_impute_lower():
    """Optional: only runs when the LWPTrends reference file was generated."""
    df = _read('lwptrends_impute_lower.csv')
    from ndimpute._ros_mixed import impute_ros_mixed
    df['censored'] = df['censored'].astype(str).str.upper() == 'TRUE'
    for _, d in df.groupby('dataset'):
        status = np.where(d['censored'].values, -1, 0)
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            out = impute_ros_mixed(d['value'].values, status, lwp_compat=True)
        np.testing.assert_allclose(out, d['lwp_i1'].values, rtol=1e-10)
